// Package attachment holds the files attached to the business need of a project (US-03): listAttachments
// and attachFile of the api. An attachment is untrusted content (RNF-05) that goes to the AI provider as an
// input of the Requisitos stage; it only enters while the project is created (US-03 RN-3, PD-12, PL-05),
// and a meeting minute pasted as text enters as a text attachment (PL-55).
package attachment

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"net/http"
	"path"
	"strings"
	"time"
	"unicode/utf8"

	"github.com/google/uuid"

	appaudit "easycode/internal/application/audit"
	appproject "easycode/internal/application/project"
	"easycode/internal/application/transaction"
	domainaudit "easycode/internal/domain/audit"
	"easycode/internal/domain/failure"
	"easycode/internal/domain/identity"
	"easycode/internal/domain/project"
)

// CodeTooLarge refuses a file above the configured limit (413 too-large-attachment, US-03 CA-4).
const CodeTooLarge = "too-large-attachment"

// Attachment is one attached file (openapi Attachment).
type Attachment struct {
	ID          string
	FileName    string
	MediaType   string
	SizeBytes   int64
	SHA256      string
	SubmittedAt time.Time
	SubmittedBy identity.Principal // Subject and Name
	// Path is the file in the files volume, generated by the platform (never from the sent name).
	Path string
}

// Repository stores the attachment records (project_attachments).
type Repository interface {
	// Insert records the attachment of the person; the project must still be created.
	Insert(ctx context.Context, principal identity.Principal, projectID string, a Attachment) (Attachment, error)
	// List returns the attachments of the project in the order they were sent.
	List(ctx context.Context, projectID string) ([]Attachment, error)
}

// Files keeps the content of the attachments (volume files).
type Files interface {
	Write(ctx context.Context, path string, content []byte) error
	Remove(ctx context.Context, path string) error
}

// Service is listAttachments and attachFile.
type Service struct {
	tx       transaction.Runner
	projects appproject.Repository
	repo     Repository
	files    Files
	trail    appaudit.Trail
	limit    int
}

// NewService builds the service; limit is the maximum size of one attachment in bytes.
func NewService(tx transaction.Runner, projects appproject.Repository, repo Repository, files Files, trail appaudit.Trail, limit int) *Service {
	return &Service{tx: tx, projects: projects, repo: repo, files: files, trail: trail, limit: limit}
}

// Limit is the maximum size of one attachment (getCurrentUser.attachment_limit_bytes).
func (s *Service) Limit() int { return s.limit }

// List is listAttachments: any role in the project (RNF-04: no role is not-found).
func (s *Service) List(ctx context.Context, principal identity.Principal, projectID string) ([]Attachment, error) {
	if _, err := appproject.Authorize(ctx, s.projects, principal, projectID); err != nil {
		return nil, err
	}
	return s.repo.List(ctx, projectID)
}

// File is a file sent to attachFile; nil content with Missing means the request had no file part.
type File struct {
	Name    string
	Content []byte
	Missing bool
	// Oversize is set when the transport already saw more bytes than the limit.
	Oversize bool
}

// Attach is attachFile: lead, approver or member, project in created (409 state-conflict after), file within
// the limit (413 too-large-attachment with limit_bytes, US-03 CA-4). The content goes to the files volume
// and the record to the trail; the media type is detected on the server, never taken from the client.
func (s *Service) Attach(ctx context.Context, principal identity.Principal, projectID string, file File) (Attachment, error) {
	access, err := appproject.Authorize(ctx, s.projects, principal, projectID, identity.RoleLead, identity.RoleApprover, identity.RoleMember)
	if err != nil {
		return Attachment{}, err
	}
	if access.State != project.StateCreated {
		return Attachment{}, failure.New(failure.KindConflict, failure.CodeStateConflict, nil).With("current_state", access.State).
			With("available_actions", []string{})
	}
	if file.Missing {
		return Attachment{}, failure.Invalid(failure.FieldError{Field: "file", Message: "required"})
	}
	if file.Oversize || len(file.Content) > s.limit {
		return Attachment{}, failure.New(failure.KindInvalidInput, CodeTooLarge, nil).With("limit_bytes", s.limit)
	}
	name, ok := FileName(file.Name)
	if !ok {
		return Attachment{}, failure.Invalid(failure.FieldError{Field: "file", Message: "file_name"})
	}
	id, err := uuid.NewRandom()
	if err != nil {
		return Attachment{}, err
	}
	sum := sha256.Sum256(file.Content)
	record := Attachment{ID: id.String(), FileName: name, MediaType: MediaType(name, file.Content), SizeBytes: int64(len(file.Content)),
		SHA256: hex.EncodeToString(sum[:]), Path: "attachments/" + projectID + "/" + id.String()}
	if err := s.files.Write(ctx, record.Path, file.Content); err != nil {
		return Attachment{}, err
	}
	var stored Attachment
	err = s.tx.InTx(ctx, func(ctx context.Context) error {
		var err error
		if stored, err = s.repo.Insert(ctx, principal, projectID, record); err != nil {
			return err
		}
		correlation, err := uuid.NewV7()
		if err != nil {
			return err
		}
		_, err = s.trail.Append(ctx, domainaudit.Record{
			ProjectID: projectID, Actor: domainaudit.Actor{Type: domainaudit.ActorHuman, ID: principal.Subject},
			Origin: domainaudit.OriginWeb, Action: "project.attach_file", Target: "attachments/" + stored.ID,
			CorrelationID: correlation.String(),
		})
		return err
	})
	if err != nil {
		_ = s.files.Remove(context.WithoutCancel(ctx), record.Path)
		return Attachment{}, err
	}
	return stored, nil
}

// FileName keeps the base name of the sent file (no directory, 1 to 255 characters, project_attachments_name_ck).
func FileName(sent string) (string, bool) {
	name := strings.TrimSpace(path.Base(strings.ReplaceAll(sent, "\\", "/")))
	if name == "" || name == "." || name == "/" || !utf8.ValidString(name) || utf8.RuneCountInString(name) > 255 ||
		strings.ContainsAny(name, "\x00\r\n") {
		return "", false
	}
	return name, true
}

// MediaType detects the media type from the content (net/http sniffing), with Markdown by extension for
// text; never the type the client declared.
func MediaType(name string, content []byte) string {
	detected := http.DetectContentType(content)
	if i := strings.IndexByte(detected, ';'); i >= 0 {
		detected = detected[:i]
	}
	detected = strings.TrimSpace(strings.ToLower(detected))
	if detected == "text/plain" {
		switch strings.ToLower(path.Ext(name)) {
		case ".md", ".markdown":
			return "text/markdown"
		case ".csv":
			return "text/csv"
		}
	}
	if detected == "" {
		return "application/octet-stream"
	}
	return detected
}
