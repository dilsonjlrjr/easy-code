// Package sandbox holds the types shared by the worker and the sandbox runner (interno.md section 2.3,
// ADR-05, ADR-06): the execution request, its limits and result, and the command allowlist of
// permissoes.yaml (command_categories), checked by the harness before asking and by the runner again.
