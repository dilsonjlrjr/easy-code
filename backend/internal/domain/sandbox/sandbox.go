// End reasons of an execution (same enumeration as the API and tool_executions.end_reason).
const (
	EndCompleted     = "completed"
	EndTimeLimit     = "time_limit"
	EndMemoryLimit   = "memory_limit"
	EndProcessLimit  = "process_limit"
	EndDiskLimit     = "disk_limit"
	EndOutputLimit   = "output_limit"
	EndAborted       = "aborted"
	EndExecutorError = "executor_error"
)

// LimitExceeded reports whether the end reason is a resource limit (US-41 CA-3, RNF-03).
func LimitExceeded(reason string) bool {
	switch reason {
	case EndTimeLimit, EndMemoryLimit, EndProcessLimit, EndDiskLimit, EndOutputLimit:
		return true
	}
	return false
}

// Categories with a meaning for the governance (gate.implementation: code.build_green, tests.executed_green).
const (
	CategoryBuild        = "build"
	CategoryTests        = "tests"
	CategoryDependencies = "install_dependencies"
	// CategoryScanner is the security scans of the Segurança (Opengrep, Trivy, Gitleaks; US-23).
	CategoryScanner = "scanner"
)

// ImageSecurity is the logical image of the security scans (infra/sandbox/security): the scanners and
// their offline databases, the same for every project stack.
const ImageSecurity = "security"

// ImageFor is the logical image an execution of the category runs in: the security image for the
// scanners, the image of the project stack for everything else (interno.md: the worker picks the image of
// the allowlist).
func ImageFor(category, stack string) string {
	if category == CategoryScanner {
		return ImageSecurity
	}
	return stack
}

