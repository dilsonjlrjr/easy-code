// ExecutionRequest asks the runner to run one command in the project workspace. There is no field for a
// docker flag, network, user, capability or runtime: all of that is constant in the runner (ADR-05/06).
type ExecutionRequest struct {
	ExecutionID string            `json:"execution_id"` // generated by the worker; idempotency key
	ProjectID   string            `json:"project_id"`
	WaveID      string            `json:"wave_id"`
	Agent       string            `json:"agent"`
	Attempt     int               `json:"attempt"`
	Image       string            `json:"image"`    // logical id of the allowlist, resolved to a digest by the runner
	Category    string            `json:"category"` // command_categories of permissoes.yaml
	Argv        []string          `json:"argv"`
	Services    []string          `json:"services"`
	Directory   string            `json:"directory"` // relative to the workspace root
	Environment map[string]string `json:"environment"`
	Limits      Limits            `json:"limits"`
}

// Limits of one execution (RNF-03). Zero means the runner default.
type Limits struct {
	CPU            float64       `json:"cpu"`
	MemoryMiB      int           `json:"memory_mib"`
	DiskMiB        int           `json:"disk_mib"`
	Processes      int           `json:"processes"`
	Time           time.Duration `json:"time"`
	MaxOutputBytes int64         `json:"max_output_bytes"`
}

// Min returns, per resource, the smaller non-zero value (effective_limits: rule min).
func (l Limits) Min(o Limits) Limits {
	pick := func(a, b float64) float64 {
		switch {
		case a == 0:
			return b
		case b == 0 || a < b:
			return a
		}
		return b
	}
	return Limits{
		CPU: pick(l.CPU, o.CPU), MemoryMiB: int(pick(float64(l.MemoryMiB), float64(o.MemoryMiB))),
		DiskMiB: int(pick(float64(l.DiskMiB), float64(o.DiskMiB))), Processes: int(pick(float64(l.Processes), float64(o.Processes))),
		Time: time.Duration(pick(float64(l.Time), float64(o.Time))), MaxOutputBytes: int64(pick(float64(l.MaxOutputBytes), float64(o.MaxOutputBytes))),
	}
}

// Within reports whether every set value is at most the ceiling.
func (l Limits) Within(ceiling Limits) bool {
	return within(l.CPU, ceiling.CPU) && within(float64(l.MemoryMiB), float64(ceiling.MemoryMiB)) &&
		within(float64(l.DiskMiB), float64(ceiling.DiskMiB)) && within(float64(l.Processes), float64(ceiling.Processes)) &&
		within(float64(l.Time), float64(ceiling.Time)) && within(float64(l.MaxOutputBytes), float64(ceiling.MaxOutputBytes))
}

func within(value, ceiling float64) bool { return ceiling == 0 || value <= ceiling }

// ExecutionResult is the outcome of an execution. ExitCode is nil when the command was killed by a limit
// or aborted.
type ExecutionResult struct {
	ExecutionID  string        `json:"execution_id"`
	Status       string        `json:"status"` // running | finished
	ExitCode     *int          `json:"exit_code"`
	EndReason    string        `json:"end_reason"`
	Start        time.Time     `json:"start"`
	End          time.Time     `json:"end"`
	Duration     time.Duration `json:"duration"`
	OutputStart  string        `json:"output_start"`
	OutputBytes  int64         `json:"output_bytes"`
	OutputSHA256 string        `json:"output_sha256"`
	Tests        *TestSummary  `json:"tests"`
	ImageDigest  string        `json:"image_digest"`
	Runtime      string        `json:"runtime"`
	Profile      string        `json:"profile"`
}

// Succeeded reports a completed command with exit code 0.
func (r ExecutionResult) Succeeded() bool {
	return r.EndReason == EndCompleted && r.ExitCode != nil && *r.ExitCode == 0
}

// TestSummary counts the tests of a test command (US-41 CA-2).
type TestSummary struct {
	Total   int `json:"total"`
	Passed  int `json:"passed"`
	Failed  int `json:"failed"`
	Skipped int `json:"skipped"`
}

// OutputStartBytes is how much of the output is kept for display (64 KiB, tool_executions.output_start).
const OutputStartBytes = 64 << 10

// Category is one entry of command_categories: the executables accepted as argv[0] and the
// argument patterns (glob over the arguments joined by spaces; empty = any argument).
type Category struct {
	Argv0           []string `json:"argv0"`
	Defaults        []string `json:"defaults"`
	Shell           bool     `json:"shell"`
	SupportServices bool     `json:"support_services"`
}

// ErrCommandNotAllowed is returned when argv does not match the category.
var ErrCommandNotAllowed = errors.New("command not allowed for the category")

// Allowed checks argv against the category (D-38): argv[0] by name, without a path; ["sh","-c",...]
// only in shell categories; the arguments must match one of the patterns when there are patterns.
func (c Category) Allowed(argv []string) error {
	if len(argv) == 0 || strings.TrimSpace(argv[0]) == "" {
		return ErrCommandNotAllowed
	}
	if argv[0] == "sh" || argv[0] == "bash" {
		if !c.Shell || len(argv) != 3 || argv[1] != "-c" || strings.TrimSpace(argv[2]) == "" {
			return ErrCommandNotAllowed
		}
		return nil
	}
	if strings.Contains(argv[0], "/") {
		return ErrCommandNotAllowed
	}
	found := false
	for _, name := range c.Argv0 {
		found = found || name == argv[0]
	}
	if !found {
		return ErrCommandNotAllowed
	}
	if len(c.Defaults) == 0 {
		return nil
	}
	args := strings.Join(argv[1:], " ")
	for _, pattern := range c.Defaults {
		if globMatch(pattern, args) {
			return nil
		}
	}
	return ErrCommandNotAllowed
}

// globMatch matches '*' as any sequence (also spaces) and every other character literally.
func globMatch(pattern, text string) bool {
	expression := "^" + strings.ReplaceAll(regexp.QuoteMeta(pattern), `\*`, ".*") + "$"
	matched, err := regexp.MatchString(expression, text)
	return err == nil && matched
}

// ForbiddenVariable reports environment names that may carry a secret (RNF-01).
var ForbiddenVariable = regexp.MustCompile(`(?i)(key|token|secret|senha|password|credential)`)

// CleanDirectory validates a workspace-relative directory: no absolute path, no "..".
func CleanDirectory(directory string) (string, bool) {
	if directory == "" || directory == "." {
		return ".", true
	}
	if strings.HasPrefix(directory, "/") || strings.Contains(directory, "\\") {
		return "", false
	}
	clean := path.Clean(directory)
	if clean == ".." || strings.HasPrefix(clean, "../") {
		return "", false
	}
	return clean, true
}
